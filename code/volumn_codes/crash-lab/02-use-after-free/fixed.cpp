// 02 - Use-After-Free 修复方案
//
// 核心原则：通过 RAII 自动管理生命周期，从根本上杜绝悬垂指针。

#include <cstdio>
#include <memory>

int main() {
    // ============================================================
    // 方案一：unique_ptr（推荐，C++11+）
    // ============================================================
    // 智能指针自动管理内存，离开作用域自动释放。
    // 释放后指针本身也不再可访问（作用域之外），从根本上杜绝 UAF。
    auto p = std::make_unique<int>(42);
    printf("unique_ptr: *p = %d\n", *p);
    // 不需要手动 delete，离开作用域自动释放
    // p 所在的作用域结束后，无法再通过 p 访问已释放内存

    // ============================================================
    // 方案二：shared_ptr（共享所有权场景）
    // ============================================================
    // 多个持有者共享同一块内存，最后一个引用消失时自动释放。
    auto shared_p = std::make_shared<int>(100);
    {
        auto copy = shared_p; // 引用计数 +1
        printf("shared_ptr: *copy = %d, use_count = %ld\n", *copy, shared_p.use_count());
    } // copy 销毁，引用计数 -1，但内存仍在（shared_p 还持有）
    printf("shared_ptr: *shared_p = %d (still valid)\n", *shared_p);

    // ============================================================
    // 方案三：栈分配（最简单，能用栈就不用堆）
    // ============================================================
    // 如果生命周期在函数内，直接用栈变量，完全避免堆管理问题。
    int stack_val = 42;
    printf("stack: val = %d\n", stack_val);

    // ============================================================
    // 防御性编程建议：
    // 1. 优先使用智能指针，禁用裸 new/delete
    // 2. 如果必须用裸指针，delete 后立即置 nullptr
    // 3. 开启 ASAN 做日常测试
    // ============================================================

    return 0;
}
